"""Train both bigram models, print how they do, and export the web playground's data.

    python scripts/train.py                 # train + export web/model.js
    python scripts/train.py --plots         # also save comparison charts to assets/
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from bigram import CountingBigram, NeuralBigram, Vocab, build_dataset, load_words, nll, sample  # noqa: E402


def export_web(path: Path, vocab: Vocab, tables: dict, words: list[str], losses: dict) -> None:
    payload = {
        "chars": vocab.chars,
        "tables": {k: [[round(float(p), 6) for p in row] for row in P.tolist()] for k, P in tables.items()},
        "losses": {k: round(v, 4) for k, v in losses.items()},
        "names": words,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "// Generated by scripts/train.py. Do not edit by hand.\n"
        f"window.BIGRAM = {json.dumps(payload, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"wrote {path.relative_to(ROOT)} ({path.stat().st_size / 1024:.0f} KB)")


def save_plots(outdir: Path, vocab: Vocab, counting: CountingBigram, neural: NeuralBigram, loss_c: float) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    outdir.mkdir(parents=True, exist_ok=True)
    N = counting.N
    n = len(vocab)

    fig, ax = plt.subplots(figsize=(16, 16))
    ax.imshow(N, cmap="Blues")
    for i in range(n):
        for j in range(n):
            ax.text(j, i, vocab.itos[i] + vocab.itos[j], ha="center", va="bottom", color="gray", fontsize=8)
            ax.text(j, i, str(N[i, j].item()), ha="center", va="top", color="gray", fontsize=8)
    ax.axis("off")
    fig.savefig(outdir / "bigram_counts.png", dpi=80, bbox_inches="tight")
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(14, 6.5))
    for ax, P, title in [
        (axes[0], counting.probs(), "Counting (smoothed N, normalised)"),
        (axes[1], neural.probs(), "Neural net (softmax of W)"),
    ]:
        im = ax.imshow(P, cmap="Blues")
        ax.set_title(title)
        ax.set_xticks(range(n), vocab.chars, fontsize=7)
        ax.set_yticks(range(n), vocab.chars, fontsize=7)
        ax.set_xlabel("next character")
        ax.set_ylabel("current character")
        fig.colorbar(im, ax=ax, shrink=0.7)
    fig.tight_layout()
    fig.savefig(outdir / "counting_vs_neural.png", dpi=90)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7, 4))
    ax.plot(neural.history, color="#2563eb")
    ax.axhline(loss_c, color="#94a3b8", ls="--", label=f"counting model ({loss_c:.3f})")
    ax.legend()
    ax.set_xlabel("training step")
    ax.set_ylabel("average NLL loss")
    ax.set_title("Neural bigram training")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(outdir / "training_loss.png", dpi=90)
    plt.close(fig)
    print(f"saved plots to {outdir.relative_to(ROOT)}/")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=ROOT / "data" / "names.txt", type=Path)
    ap.add_argument("--steps", default=1000, type=int, help="gradient descent steps for the neural model")
    ap.add_argument("--lr", default=50.0, type=float)
    ap.add_argument("--reg", default=0.0, type=float, help="weight regularisation strength (0 = none)")
    ap.add_argument("--out", default=ROOT / "web" / "model.js", type=Path)
    ap.add_argument("--plots", action="store_true", help="save charts to assets/")
    args = ap.parse_args()

    words = load_words(args.data)
    vocab = Vocab(words)
    print(f"{len(words):,} names, {len(vocab)} tokens")

    print("\n[1] counting model")
    counting = CountingBigram(vocab).fit(words)
    loss_c = nll(counting.probs(), vocab, words)
    print(f"  average NLL: {loss_c:.4f}")
    print("  samples:", ", ".join(sample(counting.probs(), vocab, n=8)))

    print("\n[2] neural model")
    xs, ys = build_dataset(words, vocab)
    print(f"  {len(xs):,} training pairs")
    neural = NeuralBigram(vocab).fit(xs, ys, steps=args.steps, lr=args.lr, reg=args.reg)
    loss_n = nll(neural.probs(), vocab, words)
    print(f"  average NLL: {loss_n:.4f}")
    print("  samples:", ", ".join(sample(neural.probs(), vocab, n=8)))

    a, b = counting.probs().flatten(), neural.probs().flatten()
    corr = ((a - a.mean()) * (b - b.mean())).sum() / ((a - a.mean()).norm() * (b - b.mean()).norm())
    print(f"\ncorrelation between the two tables: {corr.item():.6f}\n")

    export_web(
        args.out,
        vocab,
        {"counting": counting.probs(), "neural": neural.probs()},
        words,
        {"counting": loss_c, "neural": loss_n},
    )
    if args.plots:
        save_plots(ROOT / "assets", vocab, counting, neural, loss_c)


if __name__ == "__main__":
    main()
